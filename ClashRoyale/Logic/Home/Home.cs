        /// <summary>
        /// Called when the specified chest has been purchased.
        /// </summary>
        public void ChestPurchased(TreasureChestData Data, int Source, ShopChestData ShopChest = null)
        {
            if (Data == null)
            {
                Logging.Error(this.GetType(), "ChestPurchased() - chest data is NULL");
                return;
            }

            if (this.PurchasedChest != null)
            {
                Logging.Error(this.GetType(), "ChestPurchased() - Previous purchased chest not collected");
                return;
            }

            Chest Chest = new Chest(Data);
            Chest.SetSource(Source);
            Chest.ShopChest = ShopChest;

            // Rolls the reward and sends it to the client as LogicClaimRewardCommand (393); the client shows the
            // cards and echoes the command back, which applies the reward here and clears PurchasedChest.
            Chest.SetClaimed(this.GameMode, 4);

            ++this.RunningChestId;
            this.PurchasedChest = Chest;
        }

        /// <summary>
        /// Claims a purchased chest the client never confirmed (e.g. the game was closed during the opening).
        /// The 3.830 client crashes when OwnHomeData contains a pending purchased chest, so this runs at login.
        /// </summary>
        public void ClaimPendingPurchasedChest()
        {
            if (this.PurchasedChest == null)
            {
                return;
            }

            var Reward = ClashRoyale.Logic.Reward.RewardRandomizer.RandomizeReward(this.PurchasedChest, this);
            new ClashRoyale.Logic.Commands.Server.ClaimRewardCommand(Reward, 4, 14).Execute(this.GameMode);
        }

