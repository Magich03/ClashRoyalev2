        /// <summary>
        /// Increases the number of stars for star chest.
        /// </summary>
        public void IncreaseStarsToStarChest(int Count)
        {
            this.RefreshCrownChest(DateTimeOffset.UtcNow.ToUnixTimeSeconds());
            if (Count <= 0 || this.CrownChestCredits <= 0) return;
            this.StarChestCounter = Math.Min(this.StarChestCounter + Count,
                Globals.CrownChestCrownCount * this.CrownChestCredits);
            this.RefreshCrownChest(DateTimeOffset.UtcNow.ToUnixTimeSeconds());
        }

        /// <summary>
        /// Called after loading of state for refresh this instance.
        /// </summary>
        public void LoadingFinished()
        {
            this.SaveCurrentDeckTo(this.SelectedDeck);

            if (Globals.RefreshArenaInLoadingFinished)
            {
                this.GameMode.Player.RefreshArena();
            }

            this.UpdateChestCountToPlayer();
            this.UpdateCardCountToPlayer();

            if (this.GameMode.Player.IsInAlliance)
            {
                this.GameMode.AchievementManager.UpdateAchievementProgress(0, 1);
            }
        }

        /// <summary>
        /// Sets if the player claim a reward.
        /// </summary>
        public void RefreshCrownChest(long now)
        {
            int period = 3600 * Globals.CrownChestCooldownHours;
            if (NextCrownChestAt <= 0) NextCrownChestAt = now + period;
            if (now >= NextCrownChestAt)
            {
                long elapsed = (now - NextCrownChestAt) / period + 1;
                CrownChestCredits = (int)Math.Min(2L, CrownChestCredits + elapsed);
                NextCrownChestAt += elapsed * period;
            }
            CrownChestCredits = Math.Clamp(CrownChestCredits, 0, 2);
            StarChestCooldown = CrownChestCredits == 0;
            StarChestTimer.Reset();
            StarChestTimer.StartTimer((int)Math.Max(0L, NextCrownChestAt - now));
            if (!StarChestCooldown && StarChestCounter >= Globals.CrownChestCrownCount && StarChest == null)
            {
                StarChest = new Chest(GameMode.Player.Arena.StarChestData);
                StarChest.SetId(++RunningChestId);
                StarChest.UnlockDone();
            }
        }

